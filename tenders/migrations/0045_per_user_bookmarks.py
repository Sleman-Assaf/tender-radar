"""
Split the shared bookmark flag into per-user bookmarks.

`Tender.is_bookmarked` was one boolean on the tender, shared by every user: one
person starring a tender put it in all 38 users' "Bookmarked" list, and anyone
could clear it again. This creates TenderBookmark, moves the existing bookmarks
to the users who made them, and then drops the shared columns.

The old schema recorded no owner, so ownership is recovered from TenderView:
whoever had the tender open most recently before it was bookmarked is the person
who pressed the button. On this database each of the three bookmarked tenders had
been opened by exactly one user, two of them seconds before the bookmark, so the
attribution is unambiguous. Any bookmark that cannot be attributed at all is
reported and skipped rather than being handed to an arbitrary account.

The operations are ordered so the data is copied while both the old columns and
the new table exist — the autogenerated order dropped the columns first.
"""
from django.conf import settings
from django.db import migrations, models
import django.db.models.deletion
import django.utils.timezone


def _best_owner(views, bookmarked_at):
    """
    The user who most plausibly created a bookmark made at `bookmarked_at`.

    Prefers the latest view at or before the bookmark (you open a tender, then
    save it). Falls back to the view closest in time, for a bookmark made from
    the list page where no view was recorded. Returns None when the tender was
    never opened by anyone, in which case there is nothing to go on.
    """
    if not views:
        return None
    if bookmarked_at is None:
        return views[0].user_id
    earlier = [v for v in views if v.viewed_at <= bookmarked_at]
    if earlier:
        return max(earlier, key=lambda v: v.viewed_at).user_id
    return min(views,
               key=lambda v: abs((v.viewed_at - bookmarked_at).total_seconds())).user_id


def move_bookmarks_to_users(apps, schema_editor):
    from django.utils import timezone

    Tender         = apps.get_model('tenders', 'Tender')
    TenderView     = apps.get_model('tenders', 'TenderView')
    TenderBookmark = apps.get_model('tenders', 'TenderBookmark')

    moved = orphaned = 0
    for tender in Tender.objects.filter(is_bookmarked=True).iterator():
        views    = list(TenderView.objects.filter(tender_id=tender.pk))
        owner_id = _best_owner(views, tender.bookmarked_at)
        if owner_id is None:
            orphaned += 1
            print(f'  [bookmarks] tender {tender.pk}: never opened by anyone, '
                  f'no owner to assign - skipped')
            continue
        TenderBookmark.objects.get_or_create(
            tender_id=tender.pk, user_id=owner_id,
            defaults={'created_at': tender.bookmarked_at or timezone.now()},
        )
        moved += 1

    if moved or orphaned:
        print(f'  [bookmarks] moved {moved} bookmark(s) to their owners, '
              f'{orphaned} could not be attributed')


def restore_shared_flag(apps, schema_editor):
    """
    Reverse: fold every user's bookmarks back into the single shared flag.

    Per-user ownership cannot survive this — the old schema had nowhere to keep
    it. A tender saved by anybody comes back as bookmarked for everybody, which
    is exactly the behaviour this migration exists to remove.
    """
    Tender         = apps.get_model('tenders', 'Tender')
    TenderBookmark = apps.get_model('tenders', 'TenderBookmark')

    for bookmark in TenderBookmark.objects.all().order_by('created_at').iterator():
        Tender.objects.filter(pk=bookmark.tender_id).update(
            is_bookmarked=True, bookmarked_at=bookmark.created_at)


