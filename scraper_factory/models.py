class RetryPolicy(models.Model):
    """How many times, and how soon, a failing scraper is retried.

    A policy rather than a constant because failures are not equal: a portal
    behind a flaky proxy deserves several spaced retries, while a scraper whose
    selector is wrong will fail identically however often it is run. Which
    categories are worth retrying is therefore part of the policy, taken from
    the diagnostic taxonomy.
    """

    name = models.CharField(max_length=60, unique=True)
    max_attempts = models.PositiveSmallIntegerField(
        default=3, help_text="Total attempts including the first.")
    base_delay_seconds = models.PositiveIntegerField(default=300)
    backoff_multiplier = models.FloatField(
        default=2.0, help_text="Delay grows by this factor each attempt.")
    max_delay_seconds = models.PositiveIntegerField(default=7200)
    jitter_seconds = models.PositiveIntegerField(
        default=30,
        help_text="Random spread, so simultaneous failures do not retry in "
                  "lockstep and hammer a recovering portal.")

    retry_categories = models.JSONField(
        default=list, blank=True,
        help_text="Failure categories worth retrying. Empty means: retry any "
                  "transport-shaped failure and nothing else.")
    is_default = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Retry Policy"
        verbose_name_plural = "Retry Policies"
        ordering = ["-is_default", "name"]

    def __str__(self):
        return f"{self.name} ({self.max_attempts} attempts)"

    #: Transport-shaped failures: the code is probably fine, the network was not.
    TRANSIENT = ("NETWORK_ERROR", "TIMEOUT", "RATE_LIMIT", "EMPTY_RESPONSE",
                 "SSL_ERROR")

    def should_retry(self, *, attempt: int, category: str) -> bool:
        if attempt >= self.max_attempts:
            return False
        allowed = self.retry_categories or list(self.TRANSIENT)
        return (category or "") in allowed

    def delay_for(self, attempt: int) -> int:
        """Seconds to wait before attempt N+1, capped, without jitter."""
        delay = self.base_delay_seconds * (self.backoff_multiplier ** max(0, attempt - 1))
        return int(min(delay, self.max_delay_seconds))


