# ── Aggregate root ────────────────────────────────────────────────────────────

class GeneratedScraper(models.Model):
    """One scraper authored by the factory."""

    name = models.CharField(max_length=200)
    website_url = models.URLField(max_length=500)
    url_fingerprint = models.CharField(
        max_length=64, unique=True,
        help_text="SHA-256 of the normalized URL — prevents duplicate sources.",
    )
    module_name = models.CharField(
        max_length=100, unique=True,
        help_text="Module file name without .py, e.g. 'nepco_tenders'.",
    )
    class_name = models.CharField(
        max_length=100, unique=True,
        help_text="Scraper class name; must end with 'Scraper' and be free in "
                  "SCRAPER_REGISTRY.",
    )
    country = models.ForeignKey(
        "tenders.CountryConfig", on_delete=models.PROTECT,
        related_name="generated_scrapers", to_field="code",
    )
    family = models.CharField(max_length=20, choices=ScraperFamily.choices)
    status = models.CharField(max_length=20, choices=FactoryStatus.choices,
                              default=FactoryStatus.DRAFT)

    # Set at install time — a REAL active source, not a shadow row.
    scraper_source = models.OneToOneField(
        "tenders.ScraperSource", null=True, blank=True,
        on_delete=models.SET_NULL, related_name="generated_by_factory",
    )
    active_version = models.ForeignKey(
        "ScraperCodeVersion", null=True, blank=True,
        on_delete=models.SET_NULL, related_name="+",
    )
    installed_file_hash = models.CharField(max_length=64, blank=True)
    installed_at = models.DateTimeField(null=True, blank=True)
    requires_login = models.BooleanField(default=False)

    # Health, read from the existing ScrapeLog rows for this source.
    health_score = models.PositiveSmallIntegerField(default=0)
    consecutive_failures = models.PositiveSmallIntegerField(default=0)
    last_success_at = models.DateTimeField(null=True, blank=True)
    last_failure_at = models.DateTimeField(null=True, blank=True)

    created_by = models.ForeignKey(settings.AUTH_USER_MODEL,
                                   on_delete=models.PROTECT,
                                   related_name="factory_scrapers_created")
    approved_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True,
                                    on_delete=models.SET_NULL,
                                    related_name="factory_scrapers_approved")
    approved_at = models.DateTimeField(null=True, blank=True)
    review_reason = models.TextField(
        blank=True,
        help_text="Why this build was queued for developer review. Internal "
                  "only — never shown to the employee who requested it.")
    notes = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "Generated Scraper"
        ordering = ["name"]
        indexes = [
            models.Index(fields=["status"]),
            models.Index(fields=["family"]),
        ]

    def __str__(self):
        return f"{self.class_name} ({self.status})"


