class HtmlSnapshot(models.Model):
    """Stored evidence of what a website looked like at generation time (F8).

    Snapshots make generation reproducible and give the regression detector (F9)
    a baseline to diff the live site against.
    """

    class Kind(models.TextChoices):
        RAW_HTML = "RAW_HTML", "Raw HTML (no JavaScript)"
        RENDERED_DOM = "RENDERED_DOM", "Rendered DOM (browser)"
        JSON_PAYLOAD = "JSON_PAYLOAD", "JSON API payload"
        RSS_FEED = "RSS_FEED", "RSS/Atom feed"

    scraper = models.ForeignKey(GeneratedScraper, null=True, blank=True,
                                on_delete=models.CASCADE, related_name="snapshots")
    url = models.URLField(max_length=1000)
    kind = models.CharField(max_length=14, choices=Kind.choices,
                            default=Kind.RAW_HTML)
    content_hash = models.CharField(max_length=64, db_index=True)
    content_path = models.CharField(
        max_length=300, blank=True,
        help_text="Path under FACTORY_SNAPSHOT_DIR; large bodies live on disk.")
    content_inline = models.TextField(
        blank=True, help_text="Body kept inline when small enough.")
    byte_size = models.PositiveIntegerField(default=0)
    status_code = models.PositiveSmallIntegerField(null=True, blank=True)
    response_headers = models.JSONField(default=dict, blank=True)
    cookies = models.JSONField(
        default=dict, blank=True,
        help_text="Cookie NAMES only — values are never stored here.")
    dom_fingerprint = models.JSONField(
        default=dict, blank=True,
        help_text="Structural summary: tag counts, class names, table/card shape.")
    fetched_with = models.CharField(max_length=20, blank=True)
    is_baseline = models.BooleanField(
        default=False,
        help_text="The snapshot the installed scraper was generated against.")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "HTML Snapshot"
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["scraper", "-created_at"]),
            models.Index(fields=["url", "-created_at"]),
        ]

    def __str__(self):
        return f"{self.kind} {self.url[:60]} ({self.byte_size} B)"

    def body(self) -> str:
        """Return the snapshot body from inline storage or disk."""
        if self.content_inline:
            return self.content_inline
        if not self.content_path:
            return ""
        import pathlib

        from django.conf import settings
        base = getattr(settings, "FACTORY_SNAPSHOT_DIR", None)
        if base is None:
            return ""
        path = pathlib.Path(base) / self.content_path
        try:
            return path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""


